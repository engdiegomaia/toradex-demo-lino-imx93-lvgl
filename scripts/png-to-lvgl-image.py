#!/usr/bin/env python3
"""Convert a PNG into an LVGL v9 RGB565A8 C array.

GUI-Guider owns app/generated/assets/images/, so any image the project adds by
hand has to be produced outside it. This emits the same descriptor layout the
tool does (see TorizonOS_Regular_188x72_RGB565A8.c) so the two are
interchangeable at the call site.

RGB565A8 stores the whole RGB565 plane first (2 bytes per pixel, little endian)
and then the alpha plane (1 byte per pixel); header.stride is the RGB565 stride,
w * 2. Transparent pixels are forced to white before scaling so the resampler
blends edges toward the Home screen background instead of toward whatever RGB
the source happened to leave under alpha 0.

Usage:
  scripts/png-to-lvgl-image.py <in.png> <out.c> <symbol> <width> <height>
"""

import subprocess
import sys


def resample_rgba(src, width, height):
    """Scale to exactly width x height and return straight-alpha RGBA bytes."""
    argv = [
        "convert", src,
        "-background", "white", "-alpha", "background",
        "-resize", "%dx%d!" % (width, height),
        "-depth", "8",
        "RGBA:-",
    ]
    raw = subprocess.run(argv, check=True, stdout=subprocess.PIPE).stdout
    expected = width * height * 4
    if len(raw) != expected:
        raise SystemExit("convert returned %d bytes, expected %d" % (len(raw), expected))
    return raw


def to_rgb565a8(raw, width, height):
    rgb = bytearray()
    alpha = bytearray()
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i], raw[i + 1], raw[i + 2], raw[i + 3]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb.append(v & 0xFF)
        rgb.append((v >> 8) & 0xFF)
        alpha.append(a)
    return bytes(rgb) + bytes(alpha)


def emit(path, symbol, width, height, data):
    rows = []
    for off in range(0, len(data), 16):
        rows.append("  " + ", ".join("0x%02x" % b for b in data[off:off + 16]) + ",")

    guard = "LV_ATTRIBUTE_IMAGE_" + symbol.upper()
    with open(path, "w") as fp:
        fp.write(HEADER % {"symbol": symbol, "guard": guard})
        fp.write("\n".join(rows))
        fp.write(FOOTER % {
            "symbol": symbol,
            "width": width,
            "height": height,
            "stride": width * 2,
        })


HEADER = """/*
 * Copyright 2026 Toradex
 *
 * Generated by scripts/png-to-lvgl-image.py -- do not hand-edit.
 */

#ifdef __has_include
    #if __has_include("lvgl.h")
        #ifndef LV_LVGL_H_INCLUDE_SIMPLE
            #define LV_LVGL_H_INCLUDE_SIMPLE
        #endif
    #endif
#endif

#if defined(LV_LVGL_H_INCLUDE_SIMPLE)
    #include "lvgl.h"
#else
    #include "lvgl/lvgl.h"
#endif

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

#ifndef %(guard)s
#define %(guard)s
#endif

const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST %(guard)s uint8_t %(symbol)s_map[] = {
"""

FOOTER = """
};

const lv_image_dsc_t %(symbol)s = {
  .header.magic = LV_IMAGE_HEADER_MAGIC,
  .header.cf = LV_COLOR_FORMAT_RGB565A8,
  .header.stride = %(stride)d,
  .header.flags = 0,
  .header.w = %(width)d,
  .header.h = %(height)d,
  .data_size = sizeof(%(symbol)s_map),
  .data = %(symbol)s_map,
};
"""


def main():
    if len(sys.argv) != 6:
        raise SystemExit(__doc__)

    src, dst, symbol = sys.argv[1], sys.argv[2], sys.argv[3]
    width, height = int(sys.argv[4]), int(sys.argv[5])

    raw = resample_rgba(src, width, height)
    emit(dst, symbol, width, height, to_rgb565a8(raw, width, height))
    print("%s: %dx%d RGB565A8 -> %s" % (symbol, width, height, dst))


if __name__ == "__main__":
    main()
